/// 16px-based spacing scale for consistent layout.
abstract final class AppSpacing {
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double xxl = 32;

  /// Standard horizontal inset for list / form screens.
  static const double screenH = 16;

  /// Feed / detail content top padding.
  static const double screenTop = 8;

  /// Vertical gap between major sections.
  static const double section = 24;

  /// List item vertical padding (top).
  static const double listItemTop = 16;

  /// List item bottom spacing before divider.
  static const double listItemBottom = 24;
}
